"""Head angles for the Studio 3D rig animator (feat/3d-rig, PR 1; owner decision 2026-11-23).

The 3D rig draws each character's head as a flat sprite that turns with the body: front, three-quarter, side and back.
The front is the approved neutral pose. The other three are drawn by the pose-sheet image provider from the approved
neutral pose as the reference image (so the face, hair and colours match), each facing the viewer's RIGHT; the left
views are mirrored. Neutral only: expressions stay front-only.

- Nothing is generated by itself: the owner starts it, sees the cost first, and a cap refuses a request that could
  exceed it.
- Every drawing waits for the owner's approval (one approved drawing per angle; approving a new one retires the old).
- Until an angle is approved, the 3D renderer uses its mock (a squashed or hair-filled copy of the front head).
"""
from __future__ import annotations

import re
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from . import serialize as S
from .auth import current_user
from .db import get_db
from .models import Character, CharacterAsset, Event, Job
from .queue import enqueue
from .storage import storage

router = APIRouter(prefix="/api", dependencies=[Depends(current_user)])

KIND = "head-angle"
ANGLES = ("three-quarter", "side", "back")
VIEW = {
    "three-quarter": "turned to the viewer's RIGHT in a three-quarter view (about 45 degrees): both eyes visible, the far "
                     "side of the face narrower, the near ear visible",
    "side": "in full profile facing the viewer's RIGHT (90 degrees): one eye, the face outline in profile, one ear",
    "back": "seen from directly behind: the back of the head and the hair only, no face, no eyes",
}


def neutral_pose(db: Session, c: Character) -> CharacterAsset | None:
    """The approved front pose (the reference for every angle)."""
    return (db.query(CharacterAsset).filter_by(character_id=c.id, kind="pose", status="approved", expression="neutral")
            .order_by(CharacterAsset.id.desc()).first())


def approved_angles(db: Session, c: Character) -> dict[str, CharacterAsset]:
    """{angle: approved drawing}; an angle missing here uses the mock in the 3D renderer."""
    out = {}
    for a in (db.query(CharacterAsset).filter_by(character_id=c.id, kind=KIND, status="approved")
              .order_by(CharacterAsset.id.desc())):
        out.setdefault(a.expression, a)
    return out


def prompt(c: Character, angle: str) -> str:
    return (f"The attached image is THIS character ({c.name}), drawn from the front. Draw ONLY this character's HEAD (with "
            f"the top of the neck) {VIEW[angle]}. Keep everything identical to the attached image: the same drawing style, "
            "line weight, bold black outlines, flat colours, skin tone, hair shape and colour, ears and face features, and "
            "the same head size. Neutral expression. Plain flat mid-grey (#808080) background; nothing else: no body, no "
            "scenery, no shadow, no text.")


def _char(db: Session, cid: int) -> Character:
    c = db.get(Character, cid)
    if c is None:
        raise HTTPException(404, "character not found")
    return c


def busy(db: Session, c: Character) -> Job | None:
    return (db.query(Job).filter(Job.kind == "head_angles", Job.character_id == c.id, Job.status.in_(("queued", "running")))
            .order_by(Job.id.desc()).first())


def view(db: Session, c: Character) -> dict:
    from .character_looks import cost
    approved = approved_angles(db, c)
    rows = []
    for angle in ANGLES:
        review = (db.query(CharacterAsset).filter_by(character_id=c.id, kind=KIND, expression=angle, status="review")
                  .order_by(CharacterAsset.id.desc()).all())
        a = approved.get(angle)
        rows.append({"angle": angle, "status": "approved" if a else ("review" if review else "mock"),
                     "approved": {"id": a.id, "url": storage().url(a.storage_key)} if a else None,
                     "review": [{"id": r.id, "url": storage().url(r.storage_key)} for r in review]})
    front = neutral_pose(db, c)
    missing = [r["angle"] for r in rows if r["status"] == "mock"]
    job = busy(db, c)
    reason = ("locked repository artwork: new art needs the owner's separate approval" if c.locked
              else "approve the neutral pose first: it is the reference for every angle" if front is None else "")
    return {"character_id": c.id, "angles": rows, "front": {"id": front.id, "url": storage().url(front.storage_key)} if front else None,
            "missing": missing, "cost_each": cost(1), "cost_missing": cost(len(missing)) if missing else None,
            "can_generate": not reason and job is None, "reason": reason, "job": S.job(job) if job else None,
            "note": "Neutral only (expressions stay front-only). Each angle faces right; the left views are mirrored. "
                    "Until an angle is approved, the 3D renderer uses a mock made from the front head."}


@router.get("/characters/{cid}/head-angles")
def get_angles(cid: int, db: Session = Depends(get_db)):
    return view(db, _char(db, cid))


class GenerateIn(BaseModel):
    angles: list[str] = Field(min_length=1, max_length=3)
    max_usd: float = Field(gt=0, le=10)


@router.post("/characters/{cid}/head-angles/generate")
def generate(cid: int, body: GenerateIn, db: Session = Depends(get_db), user: str = Depends(current_user)):
    """The owner's click: draw the chosen angles (cost shown before; refused when it could exceed the cap)."""
    from .character_looks import cost
    from .routes_characters import require_image_generation
    c = _char(db, cid)
    require_image_generation(db, c)
    angles = list(dict.fromkeys(a for a in body.angles))
    bad = [a for a in angles if a not in ANGLES]
    if bad:
        raise HTTPException(422, f"unknown angle(s): {', '.join(bad)} (choose from {', '.join(ANGLES)})")
    if neutral_pose(db, c) is None:
        raise HTTPException(409, "approve the neutral pose first: it is the reference for every angle")
    if busy(db, c):
        raise HTTPException(409, "head angles are already being drawn for this character")
    est = cost(len(angles))
    if est["usd_high"] > body.max_usd:
        raise HTTPException(422, f"{est['text']} could exceed the ${body.max_usd:.2f} cap: choose fewer angles or raise the cap")
    job = enqueue(db, "head_angles", episode_id=c.episode_id, character_id=c.id, payload={"angles": angles, "requested_by": user})
    db.add(Event(episode_id=c.episode_id, kind="character", message=f"{c.name}: head angles requested by {user} "
                                                                    f"({', '.join(angles)}; {est['text']})"))
    db.commit()
    return {"job": S.job(job), "cost": est}


class DecisionIn(BaseModel):
    decision: str = Field(pattern="^(approve|reject)$")


@router.post("/head-angles/{aid}/decision")
def decide(aid: int, body: DecisionIn, db: Session = Depends(get_db), user: str = Depends(current_user)):
    """The owner's decision on one drawing: approve (retiring the angle's earlier approved drawing) or reject."""
    a = db.get(CharacterAsset, aid)
    if a is None or a.kind != KIND:
        raise HTTPException(404, "head angle not found")
    c = _char(db, a.character_id)
    if body.decision == "approve":
        for other in db.query(CharacterAsset).filter_by(character_id=c.id, kind=KIND, expression=a.expression, status="approved"):
            if other.id != a.id:
                other.status = "rejected"
        a.status = "approved"
    else:
        a.status = "rejected"
    db.add(Event(episode_id=c.episode_id, kind="character", message=f"{c.name}: head angle '{a.expression}' {a.status} by {user}"))
    db.commit()
    return view(db, c)


# ------------------------------------------------------------------ the job
from .tasks import Ctx, task  # noqa: E402


@task
def head_angles(ctx: Ctx) -> dict:
    """Draw each requested angle from the approved neutral pose (the identity reference); each lands in review."""
    from . import engine
    from .providers import image_generate
    from .settings_store import get_section
    from .tasks import sha256_file, style_version
    db, job = ctx.db, ctx.job
    c = db.get(Character, job.character_id)
    front = neutral_pose(db, c)
    if front is None:
        raise ValueError("no approved neutral pose to draw the head angles from")
    folder = ctx.folder("characters", c.key, "head-angles")
    ref = storage().get_to_file(front.storage_key, folder / Path(front.storage_key).name)
    cfg = get_section(db, "image")
    if cfg.get("provider") == "openai":
        cfg = {**cfg, "use_reference": True, "background": "mid-grey (#808080)"}
    version = front.style_version or style_version(db)
    made = []
    for i, angle in enumerate(job.payload.get("angles") or []):
        out = folder / f"{re.sub(r'[^a-z0-9]+', '-', angle)}-job{job.id}-a{job.attempts}.png"
        ctx.log(f"Drawing the head {angle} from the approved neutral pose (asset {front.id})")
        image_generate(cfg, prompt(c, angle), out, ref)
        if engine.make_cutout(out):
            ctx.log(f"{angle}: background removed")
        from PIL import Image
        with Image.open(out) as im:
            w, h = im.size
        key = f"characters/{c.key}/head-angles/{out.name}"
        storage().put_file(key, out, "image/png")
        a = CharacterAsset(character_id=c.id, kind=KIND, expression=angle, storage_key=key, sha256=sha256_file(out),
                           width=w, height=h, status="review", style_version=version)
        db.add(a)
        job.progress = {"done": i + 1, "total": len(job.payload.get("angles") or []), "current": angle}
        db.commit()
        made.append(a.id)
    db.add(Event(episode_id=c.episode_id, kind="character", message=f"{c.name}: {len(made)} head angle(s) ready for review"))
    db.commit()
    return {"assets": made}
