// The clean dashboard (owner-approved layout, 2026-11-25): an episode as six one-line steps, the episode list's status
// line, the episode's own characters, and what the single "Generate" button may do. Pure functions; node --test.
//
// Generate runs only FREE steps the episode allows right now and stops at
//   (a) any decision that is the owner's (approving characters, sets, script, storyboard, video, publication; labelling
//       speakers; accepting the Reference plan; choosing a set), and
//   (b) any PAID step: those only show their cost and get their own button (or open the step's own confirm).
// It never calls an approve, decide, publish, production or talking-shot endpoint: see GENERATE_FREE below.
import type {Section} from './workspace.ts';

export type StepKey = 'source' | 'characters' | 'sets' | 'storyboard' | 'video' | 'final';
export type StepState = 'done' | 'you' | 'working' | 'failed' | 'todo' | 'waiting' | 'skip';
export type Step = {n: number; key: StepKey; title: string; state: StepState; text: string; sections: Section[]};
export type Facts = {lines?: number; shots?: number; characters?: number; approvedCharacters?: number;
  setsWaiting?: number; storyboardScenes?: number};

// which workspace sections (workspace.py) make up each step; an audio episode's script is its scenes, built from the
// recording, so it sits with the storyboard
export function stepSections(audio: boolean): Record<StepKey, string[]> {
  return {
    source: audio ? ['lines', 'notes', 'people', 'plan'] : ['script'],
    characters: ['cast'],
    sets: ['set'],
    storyboard: audio ? ['script', 'storyboard'] : ['storyboard'],
    video: ['talking', 'production'],
    final: ['review', 'publishing'],
  };
}

const ORDER: StepKey[] = ['source', 'characters', 'sets', 'storyboard', 'video', 'final'];

// the worst state among a step's sections wins (a failure shows before a decision, a decision before work in progress)
const RANK: Record<string, number> = {failed: 6, action: 5, running: 4, todo: 3, waiting: 2, done: 1, not_needed: 0};
const STATE: Record<string, StepState> = {failed: 'failed', action: 'you', running: 'working', todo: 'todo',
  waiting: 'waiting', done: 'done', not_needed: 'skip'};

export const ICON: Record<StepState, string> = {done: '✓', you: '●', working: '◐', failed: '✕', todo: '○', waiting: '○', skip: '–'};
export const STEP_TONE: Record<StepState, string> = {done: 'good', you: 'warn', working: 'busy', failed: 'bad', todo: '',
  waiting: '', skip: ''};

function worst(list: Section[]): Section | null {
  return list.reduce<Section | null>((w, s) => (!w || (RANK[s.status] ?? 0) > (RANK[w.status] ?? 0) ? s : w), null);
}

function plural(n: number, one: string, many = `${one}s`): string {
  return `${n} ${n === 1 ? one : many}`;
}

// The one line a finished step shows (the counts when they are known, else the section's own note).
function doneText(key: StepKey, audio: boolean, f: Facts, fallback: string): string {
  if (key === 'source' && audio && f.lines != null) {
    return f.shots ? `analysed (${plural(f.shots, 'shot')}, ${plural(f.lines, 'line')})` : `analysed (${plural(f.lines, 'line')})`;
  }
  if (key === 'characters' && f.approvedCharacters != null) return `${f.approvedCharacters} approved`;
  if (key === 'storyboard' && f.storyboardScenes) return `${plural(f.storyboardScenes, 'scene')}, approved`;
  return fallback;
}

const TITLES = (audio: boolean): Record<StepKey, string> => ({source: audio ? 'Video' : 'Script', characters: 'Characters',
  sets: 'Sets', storyboard: 'Storyboard', video: 'Video', final: 'Final'});

const WAITING_TEXT: Record<StepKey, string> = {source: 'waiting', characters: 'after the speakers are known',
  sets: 'choose or approve a set before production', storyboard: 'one frame per shot', video: 'generated by the video tool',
  final: 'watch, approve, publish'};

export function steps(ws: any, ep: any, f: Facts = {}): Step[] {
  const audio = ep?.source === 'audio';
  const map = stepSections(audio);
  const byKey = new Map<string, Section>(((ws?.sections || []) as Section[]).map(s => [s.key, s]));
  const titles = TITLES(audio);
  return ORDER.map((key, i) => {
    const sections = map[key].map(k => byKey.get(k)).filter(Boolean) as Section[];
    const live = sections.filter(s => s.status !== 'not_needed');
    const w = worst(live);
    let state: StepState = !sections.length ? 'waiting' : !w ? 'skip' : STATE[w.status] || 'waiting';
    // a set candidate waiting for a decision is the owner's even before production needs the set
    if (key === 'sets' && (f.setsWaiting || 0) > 0 && state !== 'failed' && state !== 'done') state = 'you';
    let text = w?.note || '';
    if (state === 'done' || state === 'skip') text = doneText(key, audio, f, sections.find(s => s.status === 'done')?.note || 'not needed');
    else if (state === 'waiting') text = WAITING_TEXT[key];
    else if (key === 'sets' && (f.setsWaiting || 0) > 0) text = `${plural(f.setsWaiting!, 'set')} to approve`;
    return {n: i + 1, key, title: titles[key], state, text, sections};
  });
}

// ------------------------------------------------------------------ the list's status line
// "Waiting for you: <what>": short words for the section that needs the owner (section key and its label).
const PHRASE: Record<string, string> = {
  'lines:upload': 'upload the video', 'lines:transcribe': 'transcribe the recording', 'lines:speakers': 'label the speakers',
  'people:confirm': 'confirm who is who', 'plan:accept': 'accept the reference plan', 'cast:cast': 'cast the speakers',
  'cast:poses': 'approve character poses', 'script:review': 'approve the script', 'script:write': 'write the script',
  'script:develop': 'develop the scenes', 'script:build': 'build the scenes', 'storyboard:build': 'generate the storyboard',
  'storyboard:review': 'approve the storyboard', 'set:choose': 'approve sets', 'production:start': 'start the video',
  'review:review': 'approve the video', 'publishing:approve': 'approve publishing',
};

export function phrase(section: string, label: string, note = ''): string {
  return PHRASE[`${section}:${label}`] || note.replace(/\.$/, '').toLowerCase() || section;
}

const BUSY = ['audio_preparing', 'audio_transcribing', 'outline_generating', 'script_generating', 'storyboard_generating',
  'producing', 'publishing'];

export function listStatus(ep: any, ws?: any): {tone: string; text: string; icon: string} {
  const stage = String(ep?.stage || '');
  if (stage === 'published') return {tone: 'good', icon: '✓', text: 'Published'};
  if (stage.endsWith('_failed')) return {tone: 'bad', icon: '✕', text: `Needs attention: ${ep.next_step || stage.replace(/_/g, ' ')}`};
  if (BUSY.includes(stage)) return {tone: 'busy', icon: '◐', text: `Working: ${ep.next_step || stage.replace(/_/g, ' ')}`};
  if (ws) {
    const b = ws.blocker;
    const cur = (ws.sections || []).find((s: Section) => s.key === (b?.section || ws.current));
    if (ws.running?.length && !b) return {tone: 'busy', icon: '◐', text: `Working: ${ws.running.join(', ')}`};
    if (cur && (b || cur.status === 'action' || cur.status === 'todo')) {
      if (cur.status === 'failed') return {tone: 'bad', icon: '✕', text: `Needs attention: ${cur.title}`};
      return {tone: 'warn', icon: '●', text: `Waiting for you: ${phrase(cur.key, cur.label, cur.note)}`};
    }
    if (!ws.current) return {tone: 'good', icon: '✓', text: 'Up to date'};
  }
  if (/review|labelling|pending|approved$/.test(stage)) return {tone: 'warn', icon: '●', text: `Waiting for you: ${ep.next_step || stage}`};
  return {tone: '', icon: '○', text: ep?.next_step || stage.replace(/_/g, ' ')};
}

// ------------------------------------------------------------------ Generate
// The ONLY calls Generate may make by itself. Both are free: the scene build with the writer only when its estimate is
// exactly $0 (no text provider: the simple split; or a provider without a per-call cost), and the storyboard (a
// deterministic breakdown of the approved script plus renderer stills drawn by the studio itself).
export const GENERATE_FREE = ['/audio/scenes', '/storyboard/generate'] as const;

export type Plan =
  | {kind: 'free'; label: string; path: string; body?: unknown}
  | {kind: 'stop'; why: 'working' | 'decision' | 'paid' | 'failed' | 'done' | 'checking'; text: string};

export function money(usd: number | null | undefined): string {
  if (usd == null || !Number.isFinite(usd)) return 'cost unknown';
  return `$${usd < 0.01 ? usd.toFixed(4) : usd < 1 ? usd.toFixed(3) : usd.toFixed(2)}`;
}

// What Generate does next for this episode, or why it stops. `estimate` is /episodes/{id}/audio/scenes/estimate
// (audio episodes, before the scenes are built), or null while it loads.
export function generatePlan(ep: any, ws: any, estimate: any): Plan {
  if (!ep || !ws) return {kind: 'stop', why: 'checking', text: 'Loading…'};
  const stage = String(ep.stage);
  const can = (a: string) => (ep.allowed_actions || []).includes(a);
  const sec = (k: string) => (ws.sections || []).find((s: Section) => s.key === k) as Section | undefined;
  const active = (ep.jobs || []).some((j: any) => j.status === 'queued' || j.status === 'running');
  if (stage === 'published') return {kind: 'stop', why: 'done', text: 'Published: nothing left to generate.'};
  if (BUSY.includes(stage) || ws.running?.length || active) {
    return {kind: 'stop', why: 'working', text: ws.running?.length ? `Working: ${ws.running.join(', ')}.` : 'Working…'};
  }
  // free step 1: the scenes around the recorded lines (audio), once speakers, cast and the Reference plan are ready
  const script = sec('script');
  if (ep.source === 'audio' && stage === 'audio_labelling' && script?.status === 'action' && script.label === 'build'
      && can('build_audio_scenes')) {
    if (!estimate) return {kind: 'stop', why: 'checking', text: 'Checking what building the scenes costs…'};
    const usd = estimate.writer?.usd;
    if (usd === 0) return {kind: 'free', label: 'Building the scenes (free)', path: `/episodes/${ep.id}/audio/scenes`, body: {mode: 'writer'}};
    return {kind: 'stop', why: 'paid', text: `Building the scenes with the AI writer costs about ${money(usd)}; the simple split is free. Choose in Storyboard.`};
  }
  // free step 2: the storyboard from the approved script (deterministic, stills drawn by the studio's renderer)
  if (stage === 'script_approved' && can('generate_storyboard')) {
    return {kind: 'free', label: 'Generating the storyboard (free)', path: `/episodes/${ep.id}/storyboard/generate`};
  }
  const b = ws.blocker;
  const cur = (ws.sections || []).find((s: Section) => s.key === (b?.section || ws.current)) as Section | undefined;
  if (cur?.status === 'failed') return {kind: 'stop', why: 'failed', text: `${cur.title}: ${cur.note}`};
  const next = ws.next;
  if (next?.kind === 'paid' || (next?.kind === 'estimate' && ['talking', 'production'].includes(next.section))) {
    return {kind: 'stop', why: 'paid', text: `${next.title}: a paid step${next.cost_usd ? ` (about ${money(next.cost_usd)})` : ''}. It starts only from its own button.`};
  }
  if (cur) return {kind: 'stop', why: 'decision', text: `Waiting for you: ${phrase(cur.key, cur.label, cur.note)}.`};
  return {kind: 'stop', why: 'done', text: 'Nothing to generate right now.'};
}

// ------------------------------------------------------------------ this episode's characters
// Speakers, the silent cast and the script's characters (the full library stays on the Characters page). `cast` is
// /episodes/{id}/cast (null without a script), `audio` is /episodes/{id}/audio (null for a script-first episode).
export type EpisodeCharacter = {key: string; name: string; id?: number; status: 'approved' | 'review' | 'missing' | 'none';
  role: string; thumb?: string};

export function episodeCharacters(cast: any[] | null, audio: any | null, library: any[]): EpisodeCharacter[] {
  const lib = new Map<string, any>((library || []).map(c => [c.key, c]));
  const out = new Map<string, EpisodeCharacter>();
  const add = (key: string | null | undefined, role: string) => {
    if (!key || out.has(key)) return;
    const c = lib.get(key);
    const status = !c ? 'missing' : c.locked || c.art_status === 'approved' ? 'approved' : c.art_status === 'none' ? 'none' : 'review';
    const thumb = c?.assets?.find((a: any) => a.kind === 'pose' && a.status === 'approved')?.url;
    out.set(key, {key, name: c?.name || key, id: c?.id, status, role, thumb});
  };
  for (const r of cast || []) add(r.key, 'in the script');
  for (const s of audio?.speakers || []) add(s, 'speaks');
  for (const m of audio?.silent_cast || []) add(m.character_key, 'silent');
  // a speaker label that is not a character yet ("Speaker 1") is shown as missing until the cast is applied
  for (const s of audio?.speakers_without_character || []) if (out.get(s)?.status === 'missing') out.get(s)!.role = 'not cast yet';
  return [...out.values()];
}
