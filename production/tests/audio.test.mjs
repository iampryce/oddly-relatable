// Audio assembly. Test tones are synthesized into a temp folder at test time (test fixtures only, never assets).
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {audioPlan, buildAudioBed, measureAudio, probe} from '../lib/audio.mjs';

const needs = {skip: process.env.FFMPEG && process.env.FFPROBE ? false : 'set FFMPEG/FFPROBE'};
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'or82-audio-'));
const sha = f => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');

// Minimal 16-bit mono sine WAV writer for test inputs.
function tone(name, seconds, freq, amp, rate = 48000) {
  const n = Math.round(seconds * rate), b = Buffer.alloc(44 + n * 2), f = path.join(dir, name);
  b.write('RIFF', 0); b.writeUInt32LE(b.length - 8, 4); b.write('WAVEfmt ', 8); b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22);
  b.writeUInt32LE(rate, 24); b.writeUInt32LE(rate * 2, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34); b.write('data', 36); b.writeUInt32LE(n * 2, 40);
  for (let i = 0; i < n; i++) b.writeInt16LE(Math.round(Math.sin(2 * Math.PI * freq * i / rate) * amp * 32767), 44 + i * 2);
  fs.writeFileSync(f, b); return f;
}
const entry = (f, extra = {}) => ({source: f, sha256: sha(f), licence: 'test fixture generated by the test suite', ...extra});

test('no voice or music gives an exact-length silent bed', needs, () => {
  const plan = audioPlan(undefined, 3.5);
  const out = buildAudioBed(plan, path.join(dir, 'silent.wav'));
  assert.equal(out.kind, 'silent');
  assert.ok(Math.abs(Number(probe(out.file).format.duration) - 3.5) < 0.001);
  assert.ok(measureAudio(out.file).peakDb <= -90, 'digital silence (ffmpeg reports its -91 dB floor)');
});

test('voice clips are placed at their timestamps and music is looped, faded and trimmed to the exact duration without clipping', needs, () => {
  const voice = tone('voice.wav', 1.0, 300, 0.9), music = tone('music.wav', 0.7, 220, 0.9);
  const plan = audioPlan({voice: [entry(voice, {start: 1.5, gain: 2})], music: entry(music, {gain: 0.5})}, 4);
  const out = buildAudioBed(plan, path.join(dir, 'bed.wav'));
  const m = measureAudio(out.file);
  assert.equal(out.kind, 'mixed'); assert.equal(out.tracks, 2);
  assert.ok(Math.abs(m.duration - 4) < 0.001, `duration ${m.duration}`);
  assert.equal(m.sampleRate, 48000); assert.equal(m.channels, 2);
  assert.ok(m.peakDb < -0.5, `limiter keeps peaks below -1 dBFS (peak ${m.peakDb})`);
  // The voice is only present from 1.5 s to 2.5 s: measure a window before and inside it.
  const cut = (a, b, name) => { const f = path.join(dir, name); require_ffmpeg(['-v', 'error', '-y', '-i', out.file, '-ss', String(a), '-to', String(b), f]); return measureAudio(f).peakDb; };
  assert.ok(cut(1.6, 2.4, 'in.wav') > cut(0.5, 1.4, 'before.wav') + 3, 'voice adds level only where it is placed');
});

test('invalid audio sources are rejected with actionable messages', needs, () => {
  const f = tone('ok.wav', 0.5, 440, 0.5);
  assert.throws(() => audioPlan({voice: [{...entry(f), licence: ''}]}, 3), /"licence" is required/);
  assert.throws(() => audioPlan({voice: [{...entry(f), sha256: 'f'.repeat(64)}]}, 3), /does not match its recorded SHA-256/);
  assert.throws(() => audioPlan({voice: [{source: path.join(dir, 'nope.wav'), sha256: 'a'.repeat(64), licence: 'test'}]}, 3), /missing audio file/);
  assert.throws(() => audioPlan({voice: [{...entry(f), source: 'https://example.com/a.wav'}]}, 3), /remote sources are not allowed/);
  assert.throws(() => audioPlan({voice: [entry(f, {start: 2.8})]}, 3), /after the episode ends/);
  assert.throws(() => audioPlan({voice: [entry(f, {start: 5})]}, 3), /outside the episode/);
  assert.throws(() => audioPlan({music: entry(f, {gain: 0.9})}, 3), /gain must be in \(0, 0.5\]/);
});

import {spawnSync} from 'node:child_process';
function require_ffmpeg(args) { const r = spawnSync(process.env.FFMPEG, args, {encoding: 'utf8'}); if (r.status !== 0) throw new Error(r.stderr); }
